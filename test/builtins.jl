@testset "builtins" begin
    env = default_env()
    ev(s) = air_string(air_eval(env, read_air(s)))

    # predicates
    @test ev("(int? 3)") == "true"
    @test ev("(int? 3.0)") == "false"
    @test ev("(float? 3.0)") == "true"
    @test ev("(string? \"a\")") == "true"
    @test ev("(bool? true)") == "true"
    @test ev("(symbol? x)") == "true"
    @test ev("(keyword? :a)") == "true"
    @test ev("(wildcard? ?x)") == "true"
    @test ev("(coll? (1 2))") == "true"
    @test ev("(atom? 3)") == "true"
    @test ev("(naught? naught)") == "true"
    @test ev("(naught? ())") == "true"
    @test ev("(mut? 1)") == "false"
    @test ev("(imm? 1)") == "true"
    @test ev("(true? true)") == "true"
    @test ev("(false? false)") == "true"
    @test ev("(empty? ())") == "true"
    @test ev("(empty? 1)") == "false"
    @test ev("(complex? 1)") == "false"
    @test ev("(number? 1.5)") == "true"
    @test ev("(zero? 0)") == "true"
    @test ev("(even? 4)") == "true"
    @test ev("(odd? 3)") == "true"
    @test ev("(positive? 2)") == "true"
    @test ev("(negative? -2)") == "true"
    @test ev("(seq? (1 2))") == "true"
    @test ev("(map? (a=1))") == "true"
    @test ev("(same? 1 1)") == "true"
    @test ev("(eq? (1 2) (1 2))") == "true"
    @test ev("(contains? (a=1) :a)") == "true"
    @test ev("(member? 2 (1 2 3))") == "true"
    @test ev("(all? int? (1 2 3))") == "true"
    @test ev("(any? even? (1 3 5))") == "false"
    @test ev("(none? even? (1 3 5))") == "true"
    @test ev("(starts-with? \"abc\" \"ab\")") == "true"
    @test ev("(ends-with? \"abc\" \"bc\")") == "true"
    @test ev("(blank? ())") == "true"
    @test ev("(present? 1)") == "true"
    @test ev("(inc 2)") == "3"
    @test ev("(dec 2)") == "1"

    # collections
    @test ev("(push 10 11)") == "(10 11)"
    @test ev("(push (1 2) 3)") == "(1 2 3)"
    @test ev("(pop (1 2 3))") == "(1 2)"
    @test ev("(drop (1 2 3) 2)") == "(1 3)"
    @test ev("(length (1 2 3))") == "3"
    @test ev("(haskey (a=1) :a)") == "true"
    @test ev("(haskey (a=1) :b)") == "false"
    @test ev("(get (a=1) :b default=9)") == "9"
    @test ev("(in 2 (1 2 3))") == "true"
    @test ev("(in 9 (1 2 3))") == "false"
    @test ev("(merge (1 2) (3 4))") == "(1 2 3 4)"

    # accessors
    @test ev("(seqpart (1 2 a=3))") == "(1 2)"
    @test ev("(mappart (1 2 a=3))") == "(a=3)"

    # associative? / counted?
    @test ev("(associative? (a=1))") == "true"
    @test ev("(associative? (1 2))") == "false"
    @test ev("(counted? (1 2))") == "true"
    @test ev("(counted? \"abc\")") == "true"
    @test ev("(counted? 3)") == "false"

    # compare / hash
    @test ev("(compare 1 2)") == "-1"
    @test ev("(compare 2 1)") == "1"
    @test ev("(compare 2 2)") == "0"
    @test ev("(compare \"a\" \"b\")") == "-1"
    @test ev("(compare :a :b)") == "-1"
    @test ev("(compare (1 2) (1 3))") == "-1"
    @test ev("(number? (hash 5))") == "true"
    @test ev("(== (hash (1 2)) (hash (1 2)))") == "true"

    # keywords, symbols, and names
    @test ev("(keyword \"host\")") == ":host"
    @test ev("(keyword :host)") == ":host"
    @test ev("(symbol \"x\")") == "x"
    @test ev("(symbol (unhold '?y))") == "?y"
    @test ev("(wildcard? (symbol \"?y\"))") == "true"
    @test ev("(name :host)") == "\"host\""
    @test ev("(name ?x)") == "\"x\""
end
